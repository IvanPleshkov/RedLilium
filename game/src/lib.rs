        for path in [MENU_SCENE, LEVEL_SCENE] {
            let bytes = std::fs::read(format!("{assets_root}/{path}"))
                .expect("scene file exists — run `cargo run -p car-game --bin gen_scenes`");
            provider.insert(path, bytes);
        }
