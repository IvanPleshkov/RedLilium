//! Bake one application's vertex/fragment material, without extending engine tables.
use redlilium_graphics::{
    ShaderStage,
    shader::{ShaderLibrary, SlangCompiler},
};
use std::{fmt::Write, path::Path};

pub fn run() {
    if let Err(e) = bake(&std::env::args().skip(2).collect::<Vec<_>>()) {
        eprintln!("bake-material: {e}");
        std::process::exit(2);
    }
}
fn bake(args: &[String]) -> Result<(), Box<dyn std::error::Error>> {
    if args.len() < 2 {
        return Err("usage: bake-material INPUT.slang OUTPUT.rs [NAME=VALUE ...]".into());
    }
    let source = std::fs::read_to_string(&args[0])?;
    let defines: Vec<_> = args[2..]
        .iter()
        .map(|d| d.split_once('=').ok_or("defines must be NAME=VALUE"))
        .collect::<Result<_, _>>()?;
    let compiler = SlangCompiler::new()?;
    compiler.write_library_modules(&ShaderLibrary::standard_slang())?;
    let stages = [
        ("vs_main", ShaderStage::Vertex),
        ("fs_main", ShaderStage::Fragment),
    ];
    let mut code = vec![];
    for (entry, _) in stages {
        code.push(compiler.compile_to_wgsl(&source, entry, &[], &defines)?);
    }
    let set: Vec<_> = stages
        .iter()
        .map(|(entry, stage)| (source.as_str(), *entry, *stage, defines.as_slice()))
        .collect();
    let (layouts, rates) = compiler.reflect_all_bindings(&set)?;
    let mut out = String::from(
        "// @generated by xtask bake-material. Include as a module and call register() at startup.\n",
    );
    writeln!(out, "pub const SOURCE: &str = {source:?};")?;
    writeln!(
        out,
        "pub fn register() -> Result<(), redlilium_graphics::GraphicsError> {{\nuse redlilium_graphics::*;"
    )?;
    writeln!(out, "let sources = [")?;
    for (entry, stage) in stages {
        write!(
            out,
            "ShaderSource::slang(ShaderStage::{stage:?}, SOURCE, {entry:?}, vec!["
        )?;
        for (name, value) in &defines {
            write!(out, "({name:?}.to_owned(), {value:?}.to_owned()),")?;
        }
        writeln!(out, "]),")?;
    }
    writeln!(
        out,
        "];\nlet wgsl = vec![{:?}.to_owned(), {:?}.to_owned()];",
        code[0], code[1]
    )?;
    writeln!(out, "let layouts = vec![")?;
    for layout in layouts {
        writeln!(out, "BindingLayout {{ label: None, entries: vec![")?;
        for e in layout.entries {
            writeln!(
                out,
                "BindingLayoutEntry {{ binding: {}, binding_type: BindingType::{:?}, visibility: ShaderStageFlags::from_bits_truncate({}), label: None }},",
                e.binding,
                e.binding_type,
                e.visibility.bits()
            )?;
        }
        writeln!(out, "] }},")?;
    }
    writeln!(out, "];\nlet rates = vec![")?;
    for rate in rates {
        match rate {
            Some(rate) => writeln!(out, "Some(UpdateRate::{rate:?}),")?,
            None => writeln!(out, "None,")?,
        }
    }
    writeln!(
        out,
        "];\nshader::baked::register_shader_set(&sources, &wgsl, layouts, rates)\n}}"
    )?;
    let dest = Path::new(&args[1]);
    std::fs::write(dest, out)?;
    let status = std::process::Command::new("rustfmt")
        .arg("--edition=2024")
        .arg(dest)
        .status()?;
    if !status.success() {
        return Err("rustfmt failed".into());
    }
    Ok(())
}
